import { expect, test } from '@playwright/test'

test('edits optional fire classes on circuits and the supply cable, preserving them after regeneration and reopening', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/?fixture=priority-suite#!/projects')
  await page.locator('projects-field custom-list-item[data-name="Cadle Visual Test"]').click()
  const circuits = page.locator('project-element custom-drawer-item[data-project="00000000-0000-4000-8000-000000000104"]')
  const topology = page.locator('project-element custom-drawer-item[data-project="00000000-0000-4000-8000-000000000103"]')
  await circuits.click()
  const app = page.locator('cadle-app:not([read-only])')
  const panel = page.locator('#object-inspector')
  await expect.poll(() => app.evaluate((element: any) => element.waitForPageReady('00000000-0000-4000-8000-000000000104'))).toBe(true)
  const fireClass = 'Cca-s1,d2,a1'
  const selectCable = async () => {
    await app.evaluate(async (element: any) => { await element.exportA4PNG() })
    const point = await app.locator('g.shape-connection[data-connection-kind="cable"] .connection-conductor').first()
      .evaluate((node: SVGGeometryElement) => {
        const point = node.getPointAtLength(node.getTotalLength() * 0.6).matrixTransform(node.getScreenCTM()!)
        return { x: point.x, y: point.y }
      })
    await page.mouse.click(point.x, point.y)
    await expect(panel.getByLabel('Verbindingstype')).toHaveValue('cable')
  }
  await selectCable()
  await panel.getByLabel('Kabel-/draadtype').selectOption('XVB-Cca')
  await panel.getByLabel('Brandklasse (optioneel)').fill(fireClass)
  await panel.getByLabel('Brandklasse (optioneel)').press('Tab')
  const labels = app.locator('text.onewire-generated-label')
  await expect(labels.filter({ hasText: `XVB ${fireClass}` })).toHaveCount(1)
  await expect(labels.filter({ hasText: `XVB Cca ${fireClass}` })).toHaveCount(0)
  await app.evaluate((element: any) => element.generateAutoOneWire(1))
  await expect(labels.filter({ hasText: `XVB ${fireClass}` })).toHaveCount(1)
  await app.evaluate(async (element: any) => { await element.flushPendingSave() })
  await topology.click()
  await expect.poll(() => app.evaluate((element: any) => element.waitForPageReady('00000000-0000-4000-8000-000000000103'))).toBe(true)
  await selectCable()
  await panel.getByLabel('Brandklasse (optioneel)').fill(fireClass)
  await panel.getByLabel('Brandklasse (optioneel)').press('Tab')
  await expect(labels.filter({ hasText: `4x10 mm² EXVB ${fireClass}` })).toHaveCount(1)
  await app.evaluate(async (element: any) => { await element.flushPendingSave() })
  expect(await page.locator('app-shell').evaluate((element: any) => element.project.oneWireTopology.incomingCable.fireClass)).toBe(fireClass)
  await circuits.click()
  await expect.poll(() => app.evaluate((element: any) => element.waitForPageReady('00000000-0000-4000-8000-000000000104'))).toBe(true)
  await app.evaluate(async (element: any) => { await element.exportA4PNG() })
  await expect(labels.filter({ hasText: `XVB ${fireClass}` })).toHaveCount(1)
  const breaker = app.getByRole('img', { name: 'Automaat', exact: true }).first()
  const point = await breaker.locator('path').first().evaluate((node: SVGPathElement) => {
    const point = node.getPointAtLength(2).matrixTransform(node.getScreenCTM()!)
    return { x: point.x, y: point.y }
  })
  await page.mouse.click(point.x, point.y)
  const circuitClass = panel.locator('[data-electrical-field="cableFireClass"]')
  await expect(circuitClass).toHaveValue(fireClass)
  await circuitClass.fill('')
  await circuitClass.press('Tab')
  await expect(labels.filter({ hasText: `XVB ${fireClass}` })).toHaveCount(0)
  await expect(labels.filter({ hasText: 'XVB Cca' })).toHaveCount(1)
  await topology.click()
  await expect.poll(() => app.evaluate((element: any) => element.waitForPageReady('00000000-0000-4000-8000-000000000103'))).toBe(true)
  await app.evaluate(async (element: any) => { await element.exportA4PNG() })
  expect(await app.evaluate((element: any) => element.toSVG())).toContain(fireClass)
  await selectCable()
  await expect(panel.getByLabel('Brandklasse (optioneel)')).toHaveValue(fireClass)
  await page.screenshot({ path: '/private/tmp/cadle-cable-fire-class.png' })
})
