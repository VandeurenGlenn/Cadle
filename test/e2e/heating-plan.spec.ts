import { expect, test } from '@playwright/test'

test.use({ serviceWorkers: 'block' })

test('creates a heating plan, edits generated loops and draws persistent manual pipes', async ({ page }) => {
  await page.setViewportSize({ width: 1500, height: 1050 })
  await page.goto('/?fixture=priority-suite#!/projects')
  await page.locator('projects-field custom-list-item[data-name="Cadle Visual Test"]').click()
  const shell = page.locator('app-shell'), app = page.locator('cadle-app:not([read-only])')
  const sourceKey = '00000000-0000-4000-8000-000000000102'
  await shell.evaluate(async (element: any, key) => { await element.loadPage(key) }, sourceKey)
  const corners = [{ x: 400, y: 400 }, { x: 720, y: 400 }, { x: 720, y: 640 }, { x: 400, y: 640 }]
  const state = { version: 2, paperLayoutVersion: 1, drawingScale: 100, paperPreset: 'a4-landscape', worldWidth: 2376, worldHeight: 1680, printMargin: 10,
    selectedId: null, shapes: corners.map((start, index) => ({ id: `heat-wall-${index}`, kind: 'wall', start, end: corners[(index + 1) % 4], groupId: 'room-heating', roomName: 'Living' })) }
  await app.locator('input[type="file"][accept="application/json"]').setInputFiles({ name: 'heating-base.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(state)) })
  await expect(app.locator('[data-shape-id="heat-wall-0"]')).toBeAttached()
  await app.evaluate(async (element: any) => { await element.flushPendingSave() })
  await page.locator('project-actions').getByRole('button', { name: 'More', exact: true }).click()
  await page.locator('project-actions custom-list-item[data-action="create-heating-plan"]').click()
  await page.locator('input-form-dialog').getByRole('button', { name: 'Verdeler plaatsen', exact: true }).click()
  await expect(page.locator('.editor-header').getByRole('heading', { name: 'Legplan vloerverwarming', exact: true })).toBeVisible()
  await expect(app.locator('line.shape-wall')).toHaveCount(4)
  const heatingKey = await shell.evaluate((element: any) => element.loadedPage)
  expect(heatingKey).not.toBe(sourceKey)
  const canvasPoint = async (x: number, y: number) => app.locator('.world').evaluate((world: SVGGElement, p) => {
    const point = new DOMPoint(p.x, p.y).matrixTransform(world.getScreenCTM()!)
    return { x: point.x, y: point.y }
  }, { x, y })
  const click = async (x: number, y: number) => { const p = await canvasPoint(x, y); await page.mouse.click(p.x, p.y) }
  const toolbar = page.getByRole('toolbar', { name: 'Drawing toolbar' })
  await page.keyboard.press('Escape')
  const pickTool = async (name: string) => {
    await toolbar.getByRole('button', { name: 'More drawing tools', exact: true }).click()
    await page.getByRole('button', { name, exact: true }).click()
  }
  await pickTool('Verwarmingszone tekenen')
  const start = await canvasPoint(400, 400), end = await canvasPoint(720, 640)
  await page.mouse.move(start.x, start.y)
  await page.mouse.down()
  await page.mouse.move(end.x, end.y, { steps: 4 })
  await page.mouse.up()
  const zone = app.locator('.heating-zone')
  await expect(zone).toHaveCount(1)
  await expect(zone.locator('.heating-circuit')).toHaveCount(1)
  const inspector = page.locator('#object-inspector')
  await expect(inspector.locator('[data-heating-field="spacingMm"]')).toHaveValue('150')
  await inspector.locator('[data-heating-field="circuits"]').fill('2')
  await inspector.locator('[data-heating-field="circuits"]').press('Tab')
  await expect(zone.locator('.heating-circuit')).toHaveCount(2)
  await inspector.locator('[data-heating-field="name"]').fill('Leefruimte')
  await inspector.locator('[data-heating-field="name"]').press('Tab')
  await expect(zone).toContainText('Leefruimte')
  const beforeScale = await zone.locator('.heating-circuit').first().getAttribute('d')
  await page.getByRole('combobox', { name: 'Planschaal', exact: true }).selectOption('50')
  await expect.poll(() => zone.locator('.heating-circuit').first().getAttribute('d')).not.toBe(beforeScale)
  await expect(inspector.locator('[data-heating-field="spacingMm"]')).toHaveValue('150')
  await page.getByRole('combobox', { name: 'Planschaal', exact: true }).selectOption('100')
  await expect(zone.locator('.heating-circuit').first()).toHaveAttribute('d', beforeScale!)
  await pickTool('Verdeler plaatsen')
  await click(240, 400)
  await expect(app.locator('.heating-manifold')).toHaveCount(1)
  await expect(app.locator('.heating-manifold rect')).toHaveAttribute('fill', 'none')
  await expect(app.locator('.heating-manifold rect')).toHaveAttribute('width', '48')
  await expect(app.locator('.heating-manifold rect')).toHaveAttribute('height', '28')
  await pickTool('Verwarmingsbuis tekenen')
  await click(280, 720)
  await click(400, 720)
  await click(400, 680)
  await page.keyboard.press('Enter')
  await expect(app.locator('.heating-pipe')).toHaveCount(1)
  await inspector.locator('[data-heating-field="pipeRole"]').selectOption('return')
  await expect(app.locator('.heating-pipe .heating-circuit')).toHaveAttribute('stroke', '#175cd3')
  await app.evaluate((element: any) => element.undo())
  await expect(app.locator('.heating-pipe .heating-circuit')).toHaveAttribute('stroke', '#b42318')
  await app.evaluate((element: any) => element.redo())
  await expect(app.locator('.heating-pipe .heating-circuit')).toHaveAttribute('stroke', '#175cd3')
  await app.evaluate(async (element: any) => { await element.flushPendingSave() })
  await shell.evaluate(async (element: any, key) => { await element.loadPage(key) }, sourceKey)
  await expect(app.locator('.heating-shape')).toHaveCount(0)
  await shell.evaluate(async (element: any, key) => { await element.loadPage(key) }, heatingKey)
  await expect(app.locator('.heating-shape')).toHaveCount(3)
  await expect(zone.locator('.heating-circuit')).toHaveCount(2)
  const svg = await app.evaluate((element: any) => element.toSVG())
  expect(svg).toContain('Leefruimte')
  expect(svg).toContain('heating-manifold')
  expect(svg).toContain('Schaal 1:100')
  await app.evaluate(async (element: any) => { await element.exportA4PNG() })
  await page.screenshot({ path: '/private/tmp/cadle-heating-plan.png' })
})
